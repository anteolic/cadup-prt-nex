const assert=require('node:assert/strict');
require('./room-geometry.js');require('./grid-geometry.js');
const line=(x1,y1,x2,y2)=>({x1,y1,x2,y2});
const box=(x,y,w,h)=>[line(x,y,x+w,y),line(x+w,y,x+w,y+h),line(x+w,y+h,x,y+h),line(x,y+h,x,y)];
const outline=box(100,100,400,300);
assert.equal(GridGeometry.detect(outline.slice(0,3)).faces.length,0,'Otvoreni obris nije prostorija');
let result=GridGeometry.detect(outline);
assert.equal(result.faces.length,1);assert.equal(result.faces[0].area,120000);
let layout=RoomGeometry.layout(result.rooms);
assert.equal(layout.inner.length,0);assert.equal(Math.min(...layout.outer.map(r=>r.x)),70);
const divided=[...outline,line(300,100,300,400)];
result=GridGeometry.detect(divided);assert.equal(result.faces.length,2);
layout=RoomGeometry.layout(result.rooms);assert.equal(layout.inner[0].width,10);assert.equal(layout.area,117000);
const norm=GridGeometry.normalize(divided),index=norm.findIndex(s=>s.x1===300&&s.x2===300);
const erased=GridGeometry.erase(norm,index,200,250);
result=GridGeometry.detect(erased);assert.equal(result.faces.length,1,'Otvor u pregradi spaja prostorije');
assert.equal(RoomGeometry.layout(result.rooms).area,120000);
const gap=GridGeometry.erase(GridGeometry.normalize(outline),0,200,250);
assert.equal(GridGeometry.detect(gap).faces.length,0,'Otvor u vanjskom obrisu uklanja prostoriju');
const l=[line(100,100,500,100),line(500,100,500,300),line(500,300,300,300),line(300,300,300,500),line(300,500,100,500),line(100,500,100,100)];
result=GridGeometry.detect(l);assert.equal(result.faces[0].area,120000);assert.equal(RoomGeometry.union(result.rooms).edges.length,6);
assert.equal(GridGeometry.detect([...outline,...box(700,100,200,200)]).faces.length,2);
assert.equal(GridGeometry.detect([...outline,line(300,100,300,250)]).faces.length,1,'Slijepi rez ne dijeli prostoriju');
assert.equal(GridGeometry.detect([...outline,...outline]).faces.length,1,'Precrtavanje ne udvostručuje linije');
assert.equal(GridGeometry.detect([...outline,...box(200,200,100,100)]).faces.length,2,'Unutarnji zatvoreni obris stvara novu prostoriju');
assert.equal(GridGeometry.normalize([line(100,100,200,100),line(150,100,300,100)]).length,1);
assert.equal(GridGeometry.detect([line(100,100,300,100),line(200,0,200,400)]).faces.length,0);
const lineErased=GridGeometry.eraseLine(divided,line(300,200,300,250));
assert.equal(GridGeometry.detect(lineErased).faces.length,1);
assert.equal(GridGeometry.normalize(GridGeometry.eraseLine(outline,line(200,250,400,250))).length,4,'Gumica ne briše paralelni nepogođeni zid');
assert.equal(GridGeometry.detect(GridGeometry.eraseLine(outline,line(200,100,400,100))).faces.length,0);
const top=GridGeometry.atomic(outline).find(s=>s.y1===100&&s.y2===100);
let moved=GridGeometry.moveWall(outline,top,-50);
assert.equal(GridGeometry.detect(moved.segments).faces.length,1,'Pomak vanjskog zida čuva zatvoren obris');
assert.equal(GridGeometry.detect(moved.segments).faces[0].area,140000);
assert.equal(moved.wall.y1,50);
const middle=GridGeometry.atomic(divided).find(s=>s.x1===300&&s.x2===300);
moved=GridGeometry.moveWall(divided,middle,50);
assert.equal(GridGeometry.detect(moved.segments).faces.length,2,'Pomak pregrade zadržava dvije prostorije');
assert.equal(GridGeometry.detect(moved.segments).faces.reduce((sum,r)=>sum+r.area,0),120000);
assert.ok(GridGeometry.detect(moved.segments).faces.some(r=>r.area===75000));
moved=GridGeometry.moveWall(divided,middle,9999);
assert.equal(moved.wall.x1,495,'Zid ne može prijeći susjedni zid');
assert.equal(GridGeometry.detect(moved.segments).faces.length,2);
const partialTop=GridGeometry.atomic(divided).find(s=>s.y1===100&&s.y2===100&&s.x1===100);
const lowered=GridGeometry.moveWall(divided,partialTop,50);
assert.equal(GridGeometry.detect(lowered.segments).faces.length,2);
const returned=GridGeometry.moveWall(lowered.segments,lowered.wall,-50);
assert.equal(returned.wall.y1,100,'Spušteni segment može se točno vratiti na ravninu ostatka');
assert.equal(GridGeometry.detect(returned.segments).faces.length,2);
const shifted=GridGeometry.moveRoom(outline,GridGeometry.detect(outline).faces[0].rects,100,50);
assert.equal(GridGeometry.detect(shifted.segments).faces[0].area,120000);
assert.equal(Math.min(...shifted.segments.map(s=>s.x1)),200);
const leftFace=GridGeometry.detect(divided).faces.find(f=>f.rects.some(r=>r.x===100));
const adjacentShift=GridGeometry.moveRoom(divided,leftFace.rects,-50,50);
assert.equal(GridGeometry.detect(adjacentShift.segments).faces.length,2,'Pomak sobe prilagođava susjedne spojeve');
console.log('PASS: otvoreni i zatvoreni obrisi, L oblik, pregrade, spojevi, gumica, zidovi 30/10, preklapanje i unutarnje petlje.');

// Vrata između poravnatih pregrada odvajaju prostorije bez fizičke ispune otvora.
const doorway=[...outline,line(300,100,300,200),line(300,280,300,400)];
result=GridGeometry.detectWithDoors(doorway);
assert.equal(result.faces.length,2);assert.equal(result.doors.length,1);
layout=RoomGeometry.layout(result.rooms,GridGeometry.normalize(doorway));
assert.equal(layout.area,117800,'Oduzima se samo stvarnih 220 cm zida debljine 10 cm');
assert.ok(layout.inner.every(r=>r.width===10));
assert.ok(!layout.inner.some(r=>r.y<280&&r.y+r.height>200),'Otvor za vrata nema zid');
const horizontalDoor=[...outline,line(100,250,250,250),line(350,250,500,250)];
result=GridGeometry.detectWithDoors(horizontalDoor);assert.equal(result.faces.length,2);
assert.equal(RoomGeometry.layout(result.rooms,horizontalDoor).area,117000);
const threeRooms=[...doorway,line(100,250,180,250),line(260,250,300,250)];
assert.equal(GridGeometry.detectWithDoors(threeRooms).faces.length,3,'Više vrata prepoznaje tri prostorije');
const wideOpening=[...outline,line(300,100,300,150),line(300,300,300,400)];
result=GridGeometry.detectWithDoors(wideOpening);assert.equal(result.faces.length,1,'Otvor jednak punom dijelu zida ne dijeli prostoriju');
assert.equal(RoomGeometry.layout(result.rooms,wideOpening).inner.length,2,'Prekinuti zidovi se prikazuju i u jednoj prostoriji');
const blind=[...outline,line(300,100,300,250)];
result=GridGeometry.detectWithDoors(blind);assert.equal(result.faces.length,1);
assert.equal(RoomGeometry.layout(result.rooms,blind).inner.length,1,'Slijepa pregrada ima debljinu zida');
assert.equal(GridGeometry.detectWithDoors(gap).faces.length,0,'Ne zatvara se otvor na vanjskom obrisu');
assert.equal(GridGeometry.detectWithDoors([line(100,100,200,100),line(280,100,400,100)]).doors.length,0);
const longDoor=[...outline,line(300,100,300,180),line(300,300,300,400)];
assert.equal(GridGeometry.detectWithDoors(longDoor).faces.length,2,'Otvor od 120 cm kraći od 180 cm punog zida odvaja prostorije');
const dominantOpening=[...outline,line(300,100,300,110),line(300,210,300,250),line(300,350,300,400)];
assert.equal(GridGeometry.detectWithDoors(dominantOpening).faces.length,1,'Svaki otvor uspoređuje samo susjedne dijelove zida');
const tinyWall=[...outline,line(300,100,300,105),line(300,180,300,400)];
result=GridGeometry.detectWithDoors(tinyWall);assert.equal(result.faces.length,2);
layout=RoomGeometry.layout(result.rooms,tinyWall);
assert.ok(layout.inner.some(r=>r.x===295&&r.y===100&&r.width===10&&r.height===5),'I vrlo kratak dio ima punu debljinu zida');
const largeGap=[...outline,line(300,100,300,105),line(300,390,300,400)];
result=GridGeometry.detectWithDoors(largeGap);assert.equal(result.faces.length,1);
assert.equal(RoomGeometry.layout(result.rooms,largeGap).inner.length,2,'Kratki dijelovi se prikazuju i kad otvor ne odvaja prostorije');
console.log('PASS: otvor kraći od punog zida, tri prostorije, fizički otvori, široki prolazi i slijepe pregrade.');

const openWalls=outline.slice(0,3);
result=GridGeometry.detectWithDoors(openWalls);
assert.equal(result.faces.length,0);
const openLayout=RoomGeometry.layout(result.rooms,openWalls);
for(const s of openWalls){const x=(s.x1+s.x2)/2,y=(s.y1+s.y2)/2;assert.ok(openLayout.inner.some(r=>x>=r.x&&x<=r.x+r.width&&y>=r.y&&y<=r.y+r.height),'Nepotpuni obris prikazuje svaki nacrtani zid');}
assert.equal(RoomGeometry.layout([], [line(100,100,105,100)]).inner[0].height,10,'Samostalan kratki potez ima debljinu zida');
let resized=GridGeometry.resizeWall(divided,middle,2,280);
assert.equal(resized.wall.y2,280);
assert.ok(resized.segments.some(s=>s.x1===100&&s.y1===400&&s.x2===500),'Promjena duljine pregrade ne pomiče vanjski zid');
resized=GridGeometry.resizeWall(resized.segments,resized.wall,2,400);
assert.equal(GridGeometry.detect(resized.segments).faces.length,2,'Produženje do ruba zatvara pregradu');
resized=GridGeometry.resizeWall(divided,middle,1,9999);
assert.equal(resized.wall.y1,395,'Ručke ne mogu prijeći suprotni kraj');
